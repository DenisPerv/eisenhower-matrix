#!/usr/bin/env node
// Copies the rules block <script id="core"> of TasksDashboard.html into app/td-core.js for the phone app (app/), so both
// clients run one rule set. The body is copied unchanged under a header line; in the browser it sets window.TDCore, in Node
// it is a CommonJS module. test/app-core-parity.test.js fails when the copy is out of date.
//   node cli/sync-app-core.mjs           write app/td-core.js
//   node cli/sync-app-core.mjs --check   exit 1 when app/td-core.js differs from the block (nothing written)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const PAGE = path.join(ROOT, 'TasksDashboard.html');
export const OUT = path.join(ROOT, 'app', 'td-core.js');
export const HEADER = '// generated by cli/sync-app-core.mjs from TasksDashboard.html <script id="core">, do not edit: change the page, then run node cli/sync-app-core.mjs\n';

// the expected file text for a page's HTML
export function coreFile(html) {
  const m = String(html).match(/<script id="core">([\s\S]*?)<\/script>/);
  if (!m) throw new Error('no <script id="core"> in TasksDashboard.html');
  return HEADER + m[1].replace(/\r\n?/g, '\n').replace(/^\n/, '');
}

function main(argv) {
  const want = coreFile(fs.readFileSync(PAGE, 'utf8'));
  let have = null;
  try { have = fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n'); } catch (e) {} // a CRLF checkout counts as the same text
  if (argv.includes('--check')) {
    if (have === want) { console.log('app/td-core.js is up to date'); return 0; }
    console.error('app/td-core.js is out of date: run node cli/sync-app-core.mjs');
    return 1;
  }
  if (have === want) { console.log('app/td-core.js unchanged'); return 0; }
  fs.writeFileSync(OUT, want);
  console.log('wrote app/td-core.js (' + want.split('\n').length + ' lines)');
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
